/* This board has no AEC.
 *
 * The AtomS3R could cancel echo because one ES8311 served mic and speaker and
 * could loop the DAC back into the ADC as a reference. Here the speaker is an
 * ES8311 and the microphone an ES7243/ES7243E — two separate chips, so no such
 * reference exists. Echo is handled entirely by VAPI_ECHO_GATE below, which is
 * what actually worked on the AtomS3R anyway.
 */

/**
 * @brief  Wire audio format. Fixed, and deliberately not configurable.
 *
 * Vapi's `vapi.websocket` transport carries **raw PCM** — no Opus, no RTP.
 * Binary websocket frames are audio, text frames are JSON control messages.
 *
 * 16 kHz is the right rate and the reason is measured, not assumed: Vapi accepts
 * 16000 / 24000 / 48000 and honours all three, but its returned audio has no
 * real content above 8 kHz (measured 36 dB down at 48 kHz). Higher rates only
 * upsample, tripling bytes for nothing — and on this board bytes are WiFi
 * airtime.
 *
 * At 16 kHz / mono / s16le this is 256 kbit/s in each direction. That is ~16x
 * what Opus would cost and is the price of Vapi having no compressed-audio
 * transport that an MCU can reach; it is still comfortable on 802.11n.
 */
#define VAPI_SAMPLE_RATE   (16000)
#define VAPI_CHANNELS      (1)
#define VAPI_BITS_PER_SAMP (16)

/**
 * @brief  Audio chunk sent per websocket frame, in milliseconds.
 *
 * 20 ms (640 bytes at 16 kHz mono s16le) matches the packetisation every other
 * realtime audio path uses and keeps the send task's duty cycle predictable.
 * Larger frames cut websocket overhead but add latency in whole chunks.
 */
#define VAPI_FRAME_MS (20)

/** Bytes in one outbound audio frame. */
#define VAPI_FRAME_BYTES \
    ((VAPI_SAMPLE_RATE / 1000) * VAPI_FRAME_MS * VAPI_CHANNELS * (VAPI_BITS_PER_SAMP / 8))

