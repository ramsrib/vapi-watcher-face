/**
 * @brief  How often to look again during a call.
 *
 * One frame per call is not sight, it is a photograph. The gap shows up the
 * moment anyone asks the obvious question: "what am I holding?" — to which a
 * device with a single stale frame can only improvise, and improvising about
 * what it can see is the one thing this character must never do. Observed in
 * testing: it invented "hold it closer so I can get a good look", which sounds
 * alive and is not.
 *
 * So it looks again on a timer for as long as the call lasts. Eight seconds is
 * short enough that holding something up is noticed within a turn, and at
 * roughly seven requests for a minute-long conversation the cost stays near a
 * cent per visitor.
 *
 * Only changes are sent. Re-injecting an identical description every eight
 * seconds would fill the context with repetition and teach the model that its
 * eyes report the same thing no matter what happens.
 */
#define VLM_REFRESH_MS (8000)

/**
 * @brief  Let the call settle before the caption request handshakes.
 *
 * Not a pacing tweak — a memory one. Opening the websocket allocates its TLS
 * session and the audio buffers at the same moment, and starting a second TLS
 * handshake on top of that burst is what drove free internal heap to 7 KB and
 * made SPI DMA allocations fail elsewhere on the board.
 *
 * Costs nothing visible: the greeting is still playing, and the description is
 * only needed by the second turn.
 */
#define VLM_SETTLE_MS (1200)

/**
 * @brief  How stale a frame may be and still be worth describing.
 *
 * Generous relative to the call it serves: the frame that triggered the call is
 * milliseconds old, and the only way to approach this bound is a call started
 * by hand long after anyone was last seen — in which case describing them
 * would be wrong anyway.
 */
#define VLM_FRAME_MAX_AGE_MS (30000)

/**
 * @brief  Give up after this long.
 *
 * Short on purpose. The caption is an enhancement arriving mid-conversation —
 * if it is not there within a few seconds the moment for it has passed, and a
 * late injection is worse than none because the assistant comments on a person
 * who has already moved on. One attempt, no retry, for the same reason.
 */
#define VLM_TIMEOUT_MS (8000)

/**
 * @brief  Default speaker volume (0-100). The codec accepts up to 100; 90
 *         leaves a little headroom against distortion and current draw.
 *
 * This was 60 for a while, then 78, because echo scaled with it. That no longer
 * applies: VAPI_ECHO_GATE hard-mutes the microphone whenever the assistant is
 * audible, so however loud the speaker gets, none of it reaches Vapi. Echo
 * stopped being the constraint on loudness the moment the gate started working.
 *
 * What limits it now is physical, not acoustic:
 *   - the Echo Base speaker is small and will distort before it runs out of
 *     digital range, so back off with `vol -10` if it sounds harsh rather than
 *     merely loud;
 *   - the board is bus-powered and the amplifier draws real current. A mid-call
 *     reboot on the sibling firmware was a genuine `power-on` reset, not a
 *     crash. Running at 100 makes that likelier on a weak USB port — use a
 *     powered hub, and check the reset reason printed at boot before blaming
 *     the code.
 */
#define DEFAULT_PLAYBACK_VOL (90)

